import { Easing } from 'react-native-reanimated';

/**
 * زبانِ حرکتِ نودوست — یک منبعِ واحد برای «چطور چیزها جابه‌جا می‌شوند».
 *
 * قاعده: هر چیزی که کاربر با انگشتش گرفته، فنر است (چون جسم است)؛ هر چیزی که
 * خودبه‌خود اتفاق می‌افتد، منحنی زمانی است (چون رویداد است). قاطی‌کردنشان همان
 * چیزی است که رابط را «نرم‌افزاری» و بی‌جان نشان می‌دهد.
 */

/** فنرها — برای چیزهایی که انگشت هدایتشان می‌کند. */
export const springs = {
  /** بازگشتِ کارت به وسط، برگه‌های کشویی — کمی بازگشت دارد و حس وزن می‌دهد. */
  gentle: { damping: 18, stiffness: 170, mass: 1 },
  /** فشردنِ دکمه — باید تقریباً بلافاصله بنشیند، وگرنه لَختی حس می‌شود. */
  snappy: { damping: 20, stiffness: 380, mass: 0.6 },
  /** لحظه‌های جشن (مچ، ارتقای سطح) — بازگشتِ محسوس، عمداً نمایشی. */
  bouncy: { damping: 11, stiffness: 190, mass: 0.9 },
} as const;

/** مدت‌ها — برای چیزهایی که خودشان رخ می‌دهند. */
export const durations = {
  /** تغییرِ رنگ و شفافیت. کوتاه‌تر از این دیده نمی‌شود. */
  instant: 120,
  /** ورود و خروجِ عنصرها. */
  quick: 200,
  /** جابه‌جاییِ بزرگ‌تر، پرده‌ها. */
  base: 320,
  /** توالی‌های چندمرحله‌ای. */
  slow: 480,
} as const;

/**
 * منحنی‌ها. `exit` تندتر از `enter` است — چیزی که می‌رود نباید منتظرش بمانی،
 * ولی چیزی که می‌آید باید فرصتِ دیده‌شدن داشته باشد.
 */
export const easings = {
  enter: Easing.bezier(0.16, 1, 0.3, 1),
  exit: Easing.bezier(0.4, 0, 1, 1),
  inOut: Easing.bezier(0.65, 0, 0.35, 1),
} as const;

/** پله‌ی تأخیر برای ورودِ آبشاریِ فهرست‌ها. */
export const STAGGER = 45;

/** سقفِ تأخیرِ آبشاری — بعد از این، آیتم‌ها با هم می‌آیند تا انتها کند نشود. */
export const STAGGER_MAX = 6;

/** تأخیرِ آیتمِ n اُمِ یک فهرست. */
export const staggerDelay = (index: number) => Math.min(index, STAGGER_MAX) * STAGGER;
