import React from 'react';
import { useSession } from './SessionProvider';

/**
 * محدوده‌ی اکانتِ فعال.
 *
 * هر چیزی که به داده‌ی اکانت وابسته است (نشان‌ها، سهمیه، پیام‌های درون‌برنامه‌ای
 * و خودِ درختِ ناوبری) باید زیرِ این کامپوننت بنشیند: با عوض شدنِ اکانتِ فعال،
 * کلیدِ React عوض می‌شود و کلِ زیردرخت از نو ساخته می‌شود — یعنی هیچ کشِ
 * درون‌حافظه‌ای، شمارنده یا حالتی بین دو اکانت درز نمی‌کند.
 *
 * چرا key و نه ریستِ دستی: هر پرووایدر اگر لازم بود خودش حالتش را پاک کند،
 * یادش می‌رفت و یک به یک نشتی می‌ساختیم. کلیدِ React این تضمین را یک‌جا و
 * ساختاری میدهد: remount یعنی از صفر.
 *
 * پرووایدرهای سطحِ دستگاه (پیکربندیِ ریموت، تورِ معرفی، دروازه‌ی آپدیت) عمداً
 * بیرونِ این کلید هستند تا با سوییچِ اکانت از نو مقداردهی نشوند.
 */
export function AccountScope({ children }: { children: React.ReactNode }) {
  const { activeId } = useSession();
  return <React.Fragment key={activeId ?? 'guest'}>{children}</React.Fragment>;
}
